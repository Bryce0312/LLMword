/** Only exact factory metadata is UI. Edited or custom names remain original data. */
export function isWorkspaceBuiltinText(kind, record, field = 'name') {
  if (kind === 'role') return record?.origin === 'builtin' && Object.hasOwn(roleNames, record.agentSpecId) && record[field] === (field === 'name' ? roleNames[record.agentSpecId] : field === 'description' ? roleDescription : undefined) && record[field] !== undefined
  const tool = tools[record?.toolId ?? record?.id]
  return kind === 'tool' && tool && ['name', 'description'].includes(field) && record[field] === tool[field]
}

