function phase(text) {
  if (Object.prototype.hasOwnProperty.call(roomTranslations, text)) return known(text)
  for (const rule of roomDynamicRules.slice(-2)) if (rule.pattern.test(text)) return text.replace(rule.pattern, rule.replace)
  return text
}
